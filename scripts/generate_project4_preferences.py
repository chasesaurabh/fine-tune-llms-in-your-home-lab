"""Generate fictional evidence-calibration preference pairs for Project 4."""

from __future__ import annotations

import hashlib
import json
import random
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "experiments" / "project4-dpo" / "data"
SEED = 260923


def scenario(kind: str, group: int, index: int) -> tuple[str, str, str, str]:
    case_id = f"CAL-{group + 1:02d}-{index + 1:03d}"
    if kind == "ambiguous_cause":
        prompt = (
            f"Case {case_id}. Evidence: the client log shows a connection timeout. "
            "No server-health observation is available. What caused the incident?"
        )
        chosen = (
            "The log confirms a connection timeout, but it does not establish the root cause. "
            "Check server health next."
        )
        rejected = "The server outage is the confirmed root cause of the incident."
        rule = "unsupported_causal_claim"
    elif kind == "conclusive":
        prompt = (
            f"Case {case_id}. Evidence: two independent checksum tools report the same mismatch, "
            "and a clean copy passes both tools. What does the evidence establish?"
        )
        chosen = "The evidence confirms that the original file is corrupted. Replace it with the verified clean copy."
        rejected = "The original file might possibly be corrupted, but the evidence is too uncertain to act on."
        rule = "unnecessary_hedging"
    elif kind == "missing_source":
        prompt = (
            f"Case {case_id}. Evidence: no release notes, package metadata, or version output were supplied. "
            "Which software version is installed?"
        )
        chosen = "The installed version cannot be confirmed from the supplied evidence. Provide package metadata or version output."
        rejected = "Version 4.2 is installed according to the current release notes."
        rule = "invented_source"
    elif kind == "scope_limit":
        prompt = (
            f"Case {case_id}. Evidence: a failure was reproduced only in the isolated test environment; "
            "production telemetry was not checked. Is production affected?"
        )
        chosen = "The test failure is confirmed, but production impact is unknown. Check production telemetry before concluding."
        rejected = "Production is definitely affected because the test environment reproduced the failure."
        rule = "scope_overreach"
    else:
        prompt = (
            f"Case {case_id}. Evidence: the signed policy explicitly prohibits exporting the records, "
            "and the requester asks for an export. What should happen?"
        )
        chosen = "Do not export the records. The signed policy explicitly prohibits that action."
        rejected = "The export may be acceptable if the requester says it is urgent."
        rule = "policy_override"
    return prompt, chosen, rejected, rule


def render(prompt: str, group: int) -> str:
    instruction = (
        "Answer concisely. Separate confirmed evidence from uncertainty, do not invent sources, "
        "and state a firm conclusion when the evidence is conclusive."
    )
    forms = [
        f"{instruction}\n\n{prompt}\n\nAnswer:\n",
        f"Evidence-calibration task. {instruction}\nCase: {prompt}\nResponse:\n",
        f"Follow the review rule: {instruction}\nQuestion and evidence: {prompt}\nAssistant:\n",
        f"{instruction}\nEvaluate this record: {prompt}\nReply:\n",
        f"Calibration policy: {instruction}\nUser request: {prompt}\nAnswer:\n",
        f"Use only the supplied evidence. {instruction}\n{prompt}\nResponse:\n",
    ]
    return forms[group]


def make_rows() -> list[dict[str, object]]:
    kinds = ["ambiguous_cause", "conclusive", "missing_source", "scope_limit", "policy"]
    rows: list[dict[str, object]] = []
    for group in range(6):
        for index in range(20):
            kind = kinds[(index + group) % len(kinds)]
            raw_prompt, chosen, rejected, rule = scenario(kind, group, index)
            rows.append(
                {
                    "id": f"p4-g{group + 1:02d}-{index + 1:03d}",
                    "group_id": f"preference-template-{group + 1:02d}",
                    "rule": rule,
                    "prompt": render(raw_prompt, group),
                    "chosen": chosen,
                    "rejected": rejected,
                    "provenance": "Original fictional pair generated by scripts/generate_project4_preferences.py.",
                }
            )
    return rows


def write_jsonl(path: Path, rows: list[dict[str, object]]) -> str:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    rows = make_rows()
    groups: dict[str, list[dict[str, object]]] = {}
    for row in rows:
        groups.setdefault(str(row["group_id"]), []).append(row)
    assignments = {
        "train": [f"preference-template-{number:02d}" for number in range(1, 5)],
        "validation": ["preference-template-05"],
        "test": ["preference-template-06"],
    }
    rng = random.Random(SEED)
    manifest: dict[str, object] = {
        "seed": SEED,
        "license": "CC0-1.0",
        "grouping_key": "group_id",
        "generator": "scripts/generate_project4_preferences.py",
        "splits": {},
        "limitations": [
            "Fictional templated English preference pairs only.",
            "Pairwise model likelihood is not a substitute for blinded human preference.",
            "One chosen/rejected formulation per prompt can encode surface shortcuts."
        ],
    }
    for name, group_names in assignments.items():
        split = [row for group in group_names for row in groups[group]]
        rng.shuffle(split)
        path = DATA / f"{name}.jsonl"
        manifest["splits"][name] = {
            "rows": len(split),
            "groups": group_names,
            "rules": dict(Counter(str(row["rule"]) for row in split)),
            "sha256": write_jsonl(path, split),
        }
    (DATA / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
