"""Generate the fictional terminology-and-style dataset for Project 2."""

from __future__ import annotations

import hashlib
import json
import random
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "experiments" / "project2-nvidia" / "data"
SEED = 260921

TERMS = {
    "Lumen queue": "the nightly batch list",
    "Harbor token": "a read-only access credential",
    "Ember window": "the scheduled maintenance period",
    "Northstar note": "a one-sentence status summary",
    "Quiet flag": "a temporary suppression of noncritical alerts",
}


def fact_for(term: str, group: int, index: int) -> tuple[str, str, str]:
    if term == "Lumen queue":
        value = f"{18 + (group + index) % 6:02d}:00 UTC"
        return (
            f"The Lumen queue closes at {value}.",
            "When does the Lumen queue close?",
            f"it closes at {value}",
        )
    if term == "Harbor token":
        value = 5 + (group * 3 + index) % 25
        return (
            f"The Harbor token expires after {value} days.",
            "How long is the Harbor token valid?",
            f"it is valid for {value} days",
        )
    if term == "Ember window":
        days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
        day = days[(group + index) % len(days)]
        hour = 1 + (group * 2 + index) % 5
        value = f"{day} at {hour:02d}:00 UTC"
        return (
            f"The Ember window starts {value}.",
            "When does the Ember window start?",
            f"it starts {value}",
        )
    if term == "Northstar note":
        value = 12 + (group + index) % 19
        return (
            f"The Northstar note may contain at most {value} words.",
            "What is the Northstar note length limit?",
            f"its limit is {value} words",
        )
    value = 10 + (group * 5 + index) % 50
    return (
        f"The Quiet flag remains active for {value} minutes.",
        "How long does the Quiet flag remain active?",
        f"it remains active for {value} minutes",
    )


def prompt(context: str, question: str, template: int) -> str:
    instruction = (
        "Use exactly two sentences. In sentence one, define the named house term using the glossary. "
        "In sentence two, begin with 'Based on the supplied context,' and answer only from the context. "
        "Do not add a heading or unsupported fact."
    )
    forms = [
        f"{instruction}\n\nGlossary and context:\n{context}\n\nQuestion: {question}\n\nAnswer:",
        f"House-style task. {instruction}\nContext: {context}\nRequest: {question}\nResponse:",
        f"Follow this response contract: {instruction}\nEvidence: {context}\nUser asks: {question}\nAssistant:",
        f"{instruction}\nRetrieved passage: {context}\nQuestion from the reader: {question}\nWrite the answer:",
        f"Style rule: {instruction}\nThe only factual source is: {context}\n{question}\nAnswer:",
        f"Respond under the house terminology policy. {instruction}\nSupplied material: {context}\nPrompt: {question}\nResponse:",
    ]
    # Preserve a visible token boundary before the completion-only target.
    return forms[template] + "\n"


def make_rows() -> list[dict[str, object]]:
    terms = list(TERMS)
    rows: list[dict[str, object]] = []
    for group in range(6):
        for index in range(30):
            term = terms[(index + group) % len(terms)]
            definition = TERMS[term]
            fact, question, answer = fact_for(term, group, index)
            context = f"Glossary: {term} means {definition}. Current fact: {fact}"
            target = f"{term} means {definition}. Based on the supplied context, {answer}."
            rows.append(
                {
                    "id": f"p2-g{group + 1:02d}-{index + 1:03d}",
                    "group_id": f"style-template-{group + 1:02d}",
                    "term": term,
                    "definition": definition,
                    "grounded_answer": answer,
                    "context": context,
                    "question": question,
                    "prompt": prompt(context, question, group),
                    "completion": target,
                    "target": target,
                    "provenance": "Original fictional data generated by scripts/generate_project2_dataset.py.",
                }
            )
    return rows


def write_jsonl(path: Path, rows: list[dict[str, object]]) -> str:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    rows = make_rows()
    by_group: dict[str, list[dict[str, object]]] = {}
    for row in rows:
        by_group.setdefault(str(row["group_id"]), []).append(row)
    split_groups = {
        "train": [f"style-template-{number:02d}" for number in range(1, 5)],
        "validation": ["style-template-05"],
        "test": ["style-template-06"],
    }
    rng = random.Random(SEED)
    manifest: dict[str, object] = {
        "seed": SEED,
        "license": "CC0-1.0",
        "grouping_key": "group_id",
        "generator": "scripts/generate_project2_dataset.py",
        "splits": {},
        "limitations": [
            "Fictional templated English data only.",
            "Automated style proxies do not replace blind human review.",
            "This dataset is tied to the recorded NVIDIA harness and does not imply alternate-runtime equivalence."
        ],
    }
    for name, groups in split_groups.items():
        split = [row for group in groups for row in by_group[group]]
        rng.shuffle(split)
        path = DATA / f"{name}.jsonl"
        manifest["splits"][name] = {
            "rows": len(split),
            "groups": groups,
            "terms": dict(Counter(str(row["term"]) for row in split)),
            "sha256": write_jsonl(path, split),
        }
    (DATA / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
