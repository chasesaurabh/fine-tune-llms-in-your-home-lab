"""Generate a larger grouped synthetic dataset for Project 1 evidence runs."""

from __future__ import annotations

import hashlib
import json
import random
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "experiments" / "nvidia-evidence" / "data"
SEED = 260916

CATEGORIES = {
    "network": [
        "the inventory portal cannot be reached",
        "wireless connections drop repeatedly",
        "the router reports that its uplink is down",
        "name lookups time out",
        "remote sessions disconnect after a few seconds",
    ],
    "hardware": [
        "the monitor flickers after warming up",
        "the workstation does not power on",
        "the keyboard repeats characters",
        "the storage warning indicator is illuminated",
        "the cooling fan makes a grinding sound",
    ],
    "software": [
        "the reporting application closes during export",
        "the desktop client loops during sign-in",
        "the accounting application reports an update failure",
        "the editor freezes while opening a project",
        "the approved plugin fails to load",
    ],
    "access": [
        "the user is locked out after changing a password",
        "the shared folder returns permission denied",
        "the new employee cannot open the mailbox",
        "the service-account token has been revoked",
        "the approved group is missing from the account",
    ],
}

URGENCY = {
    "low": [
        "There is a working alternative and no deadline.",
        "This may wait for the scheduled maintenance window.",
        "The issue is inconvenient but no work is blocked.",
    ],
    "medium": [
        "One person is blocked while the rest of the team continues.",
        "Please investigate before the end of the day.",
        "A time-sensitive task is delayed, but a partial workaround exists.",
    ],
    "high": [
        "Production work has stopped and there is no workaround.",
        "The entire team is blocked.",
        "A critical operation cannot continue.",
    ],
}

PROMPT = (
    "Extract exactly one JSON object with string keys category, urgency, and asset. "
    "Allowed category values: network, hardware, software, access. "
    "Allowed urgency values: low, medium, high. "
    "Use the asset identifier exactly as written. Return no prose.\n\nNote: {note}\n\nJSON:"
)


def render(group: int, asset: str, issue: str, urgency: str) -> str:
    templates = [
        "Asset {asset}. Report: {issue}. Impact: {urgency}",
        "{urgency} The affected device is {asset}; {issue}.",
        "Ticket for {asset}: {issue}. The reporter adds: {urgency}",
        "Device={asset}. Observed condition: {issue}. Business impact: {urgency}",
        "Regarding {asset}, the technician notes that {issue}. {urgency}",
        "Impact statement: {urgency} Incident on {asset}: {issue}.",
        "Please classify this report. {asset} is affected because {issue}. {urgency}",
        "The note concerns {asset}. {urgency} Symptom: {issue}.",
        "A report says: {issue}. Identifier {asset}. The impact is described as follows: {urgency}",
        "For equipment {asset}, we observed this condition: {issue}. Separately, {urgency}",
        "Classification request -- identifier {asset}; condition {issue}; impact {urgency}",
        "Here are the facts. First, {urgency} Second, on {asset}, {issue}.",
    ]
    return templates[group].format(asset=asset, issue=issue, urgency=urgency)


def make_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    labels = list(CATEGORIES)
    urgency_labels = list(URGENCY)
    for group in range(12):
        for index in range(30):
            category = labels[(index + group) % len(labels)]
            urgency = urgency_labels[(index + 2 * group) % len(urgency_labels)]
            issue = CATEGORIES[category][(index // 4 + group) % len(CATEGORIES[category])]
            urgency_text = URGENCY[urgency][(index // 3 + group) % len(URGENCY[urgency])]
            asset = f"EVID-{group + 1:02d}-{index + 1:03d}"
            target = {"category": category, "urgency": urgency, "asset": asset}
            rows.append(
                {
                    "id": f"evidence-g{group + 1:02d}-{index + 1:03d}",
                    "group_id": f"phrase-family-{group + 1:02d}",
                    "asset_group": asset,
                    "category_slice": category,
                    "urgency_slice": urgency,
                    "prompt": PROMPT.format(
                        note=render(group, asset, issue, urgency_text)
                    ),
                    "completion": json.dumps(target, separators=(",", ":"), sort_keys=True),
                    "target": target,
                    "provenance": (
                        "Generated by scripts/generate_extraction_evidence_dataset.py; "
                        "original synthetic text; no external source records."
                    ),
                }
            )
    return rows


def write_jsonl(path: Path, rows: list[dict[str, object]]) -> str:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    rows = make_rows()
    by_group = {f"phrase-family-{number:02d}": [] for number in range(1, 13)}
    for row in rows:
        by_group[str(row["group_id"])].append(row)

    rng = random.Random(SEED)
    train_groups = [f"phrase-family-{number:02d}" for number in range(1, 9)]
    validation_groups = ["phrase-family-09", "phrase-family-10"]
    test_groups = ["phrase-family-11", "phrase-family-12"]
    splits = {
        "train": [row for group in train_groups for row in by_group[group]],
        "validation": [row for group in validation_groups for row in by_group[group]],
        "test": [row for group in test_groups for row in by_group[group]],
    }
    for split in splits.values():
        rng.shuffle(split)

    manifest: dict[str, object] = {
        "seed": SEED,
        "license": "CC0-1.0",
        "generator": "scripts/generate_extraction_evidence_dataset.py",
        "grouping_key": "group_id",
        "group_assignment": {
            "train": train_groups,
            "validation": validation_groups,
            "test": test_groups,
        },
        "splits": {},
        "limitations": [
            "Fully synthetic templated dataset; it does not represent real support traffic.",
            "Held-out phrase families test limited structural generalization only.",
        ],
    }
    for name, split in splits.items():
        path = DATA_DIR / f"{name}.jsonl"
        digest = write_jsonl(path, split)
        manifest["splits"][name] = {
            "rows": len(split),
            "sha256": digest,
            "groups": sorted({str(row["group_id"]) for row in split}),
            "categories": dict(Counter(str(row["category_slice"]) for row in split)),
            "urgencies": dict(Counter(str(row["urgency_slice"]) for row in split)),
        }
    (DATA_DIR / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
